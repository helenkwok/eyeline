"""
bench/sync_state.py — Programmatic STATE.md Scoreboard Injector for Eyeline.

Reads a provenanced scorecard JSON produced by bench/run_benchmark.py and
injects an auto-generated empirical scoreboard section into docs/STATE.md,
replacing everything between the sentinel comments:

    <!-- BEGIN EMPIRICAL SCOREBOARD -->
    <!-- END EMPIRICAL SCOREBOARD -->

This guarantees that numbers in STATE.md are never hand-typed.

Usage:
    python3 -m bench.sync_state
    python3 -m bench.sync_state --scorecard-path bench/fixtures/scorecard.json \\
                                 --state-file docs/STATE.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

# Sentinel comments that bracket the auto-managed scoreboard section.
_BEGIN_SENTINEL = "<!-- BEGIN EMPIRICAL SCOREBOARD -->"
_END_SENTINEL = "<!-- END EMPIRICAL SCOREBOARD -->"


# ---------------------------------------------------------------------------
# Provenance validation
# ---------------------------------------------------------------------------


def _assert_provenance(scorecard: dict) -> dict:
    """
    Assert that scorecard contains a non-empty detector_provenance block.

    Returns the provenance dict on success; raises ValueError on failure.
    """
    prov = scorecard.get("detector_provenance")
    if not prov or not isinstance(prov, dict):
        raise ValueError(
            "Scorecard JSON lacks a valid 'detector_provenance' block. "
            "Run 'python3 -m bench.run_benchmark' to generate a provenanced scorecard."
        )
    if not prov.get("detector"):
        raise ValueError(
            "detector_provenance.detector is empty in the scorecard. "
            "Refusing to sync unprovenanced numbers into STATE.md."
        )
    return prov


# ---------------------------------------------------------------------------
# Markdown generation
# ---------------------------------------------------------------------------


def _build_scoreboard_markdown(scorecard: dict, prov: dict) -> str:
    """Render the full scoreboard markdown block (excluding sentinel lines)."""
    tp = scorecard.get("true_positives", 0)
    p = scorecard.get("defect_pairs_total", 0)
    tp_loc = scorecard.get("localized_true_positives", 0)
    spatial = scorecard.get("spatial_defects_total", 0)
    fp = scorecard.get("false_positives", 0)
    c = scorecard.get("control_pairs_total", 0)
    fn = scorecard.get("false_passes", 0)
    recall_pct = scorecard.get("recall_percent", 0.0)
    loc_pct = scorecard.get("localisation_percent", 0.0)
    fpr_pct = scorecard.get("fpr_percent", 0.0)
    headline = scorecard.get("headline_statement", "")
    run_ts = prov.get("run_timestamp", "unknown")
    detector = prov.get("detector", "unknown")
    pipeline = prov.get("pipeline_stage", "unknown")
    media_fmt = prov.get("media_format", "unknown")

    tripped_controls = scorecard.get("tripped_controls", [])
    missed_defects = scorecard.get("missed_defects", [])

    lines = [
        "> [!NOTE]",
        "> **EMPIRICALLY MEASURED — ZERO HAND-WRITTEN NUMBERS**  ",
        f"> Generated by `{detector}` at `{run_ts}`.  ",
        f"> Pipeline: {pipeline} · Media: {media_fmt}  ",
        "> Full predictions: `bench/fixtures/measured_predictions.json`; scorecard: `bench/fixtures/scorecard.json`.",
        "",
        "| Metric | Measured Value | Formula | Meaning |",
        "|---|---|---|---|",
        f"| **Defect Detection Recall** | **{tp} / {p} = {recall_pct:.1f}%** | $TP / P$ | Seeded continuity defects caught by classical CV. |",
        f"| **Spatial Localisation Accuracy** | **{tp_loc} / {spatial} = {loc_pct:.1f}%** | $TP_{{\\text{{loc}}}} / TP_{{\\text{{spatial}}}}$ ($IoU \\ge 0.3$) | Defects accurately localized within ground-truth bounds. |",
        f"| **Control False-Positive Rate** | **{fp} / {c} = {fpr_pct:.1f}%** | $FPR = FP / C$ | Classical CV delta rate on controls (before Gemini adjudication). |",
        f"| **False Passes (Escaped Defects)** | **{fn} / {p}** | $FN = P - TP$ |"
        + (f" Escaped: {', '.join(f'`{m}`' for m in missed_defects)}." if missed_defects else " None.") + " |",
        "",
        "### Canonical Benchmark Statement:",
        f"> *\"{headline}\"*",
    ]

    if tripped_controls:
        lines += [
            "",
            "### Tripped Controls Catalogue",
            "",
            "| pair_id | template | category | confidence |",
            "|---------|----------|----------|-----------|",
        ]
        for t in tripped_controls:
            conf = t.get("confidence")
            conf_str = f"{conf:.2f}" if conf is not None else "—"
            lines.append(
                f"| `{t['pair_id']}` | {t.get('template_id', '—')} | {t.get('category', '—')} | {conf_str} |"
            )

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# STATE.md injection
# ---------------------------------------------------------------------------


def inject_scoreboard(scorecard_path: str, state_file: str) -> None:
    """
    Read scorecard JSON, validate provenance, and replace the sentinel-bracketed
    scoreboard section in STATE.md with freshly generated markdown.
    """
    sc_path = Path(scorecard_path)
    if not sc_path.exists():
        raise FileNotFoundError(f"Scorecard not found: {sc_path.resolve()}")

    scorecard = json.loads(sc_path.read_text(encoding="utf-8"))
    prov = _assert_provenance(scorecard)

    st_path = Path(state_file)
    if not st_path.exists():
        raise FileNotFoundError(f"STATE.md not found: {st_path.resolve()}")

    original = st_path.read_text(encoding="utf-8")

    begin_idx = original.find(_BEGIN_SENTINEL)
    end_idx = original.find(_END_SENTINEL)

    if begin_idx == -1 or end_idx == -1:
        raise ValueError(
            f"Sentinel comments not found in {state_file}.\n"
            f"Add:\n  {_BEGIN_SENTINEL}\n  {_END_SENTINEL}\n"
            "around the scoreboard section."
        )
    if end_idx <= begin_idx:
        raise ValueError("END sentinel appears before BEGIN sentinel in STATE.md.")

    body = _build_scoreboard_markdown(scorecard, prov)

    # Preserve text before BEGIN sentinel and after END sentinel (including the sentinels).
    before = original[: begin_idx + len(_BEGIN_SENTINEL)]
    after = original[end_idx:]  # starts with END sentinel

    updated = before + "\n" + body + "\n" + after
    st_path.write_text(updated, encoding="utf-8")
    print(f"STATE.md scoreboard updated from {sc_path} (run: {prov.get('run_timestamp')})")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Sync empirical scorecard numbers into docs/STATE.md"
    )
    parser.add_argument(
        "--scorecard-path",
        default="bench/fixtures/scorecard.json",
        help="Path to scorecard JSON produced by bench/run_benchmark.py "
             "(default: bench/fixtures/scorecard.json)",
    )
    parser.add_argument(
        "--state-file",
        default="docs/STATE.md",
        help="Path to docs/STATE.md (default: docs/STATE.md)",
    )
    args = parser.parse_args()

    try:
        inject_scoreboard(args.scorecard_path, args.state_file)
    except (FileNotFoundError, ValueError) as exc:
        sys.exit(f"Error: {exc}")


if __name__ == "__main__":
    main()
